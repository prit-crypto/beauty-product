def t(lang: str, key: str, _v: int = 0, **kw) -> str:
    """Template text. `_v` picks a variant (e.g. the turn number) so repeated replies don't sound identical."""
    s = T.get(lang, T["en"]).get(key) or T["en"][key]
    if isinstance(s, list):
        s = s[_v % len(s)]
    return s.format(**kw) if kw else s


def all_variants(lang: str, key: str) -> list[str]:
    s = T.get(lang, T["en"]).get(key) or T["en"][key]
    return s if isinstance(s, list) else [s]


def slot_label(lang: str, slot: str) -> str:
    return SLOT_LABELS.get(lang, {}).get(slot, slot)


def join_list(lang: str, items: list[str]) -> str:
    items = [i for i in items if i]
    if len(items) <= 1:
        return "".join(items)
    if lang == "ar":
        return "، ".join(items[:-1]) + " و" + items[-1]
    return ", ".join(items[:-1]) + " " + t(lang, "and") + " " + items[-1]
